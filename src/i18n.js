// ---- The interface's language: English, Portuguese or Spanish.
// The page's own text is English in the HTML (elements marked data-t="<id>", placeholders data-t-ph="<id>"), with its
// Portuguese in PT_HTML; the code's strings are English, wrapped in T(), with their Portuguese in PT (keyed by the English).
const UI_LANGS = { en: 'English', pt: 'Português', es: 'Español' };
let UI_LANG = (() => { try { const l = localStorage.getItem('customkits-lang'); return l in UI_LANGS ? l : 'en'; } catch (e) { return 'en'; } })();
// T('Kit {n} of {t}', { n: 1, t: 3 }): the string in the interface's language, with its {fields} filled in
function T(s, p) {
  const d = UI_LANG === 'pt' ? PT : UI_LANG === 'es' ? ES : null;
  let r = d && d[s] != null ? d[s] : s;
  if (p) r = r.replace(/\{(\w+)\}/g, (m, k) => (k in p ? p[k] : m));
  return r;
}
const htmlT = id => { const d = UI_LANG === 'pt' ? PT_HTML : UI_LANG === 'es' ? ES_HTML : null; return d && d[id] != null ? d[id] : null; };
function applyStatic() {
  document.documentElement.lang = UI_LANG;
  for (const e of document.querySelectorAll('[data-t]')) {
    if (e.dataset.en == null) e.dataset.en = e.innerHTML;
    e.innerHTML = htmlT(e.dataset.t) ?? e.dataset.en;
  }
  for (const e of document.querySelectorAll('[data-t-ph]')) {
    if (e.dataset.enPh == null) e.dataset.enPh = e.placeholder;
    e.placeholder = htmlT(e.dataset.tPh) ?? e.dataset.enPh;
  }
}
function setLang(l) {
  UI_LANG = l in UI_LANGS ? l : 'en';
  try { localStorage.setItem('customkits-lang', UI_LANG); } catch (e) { /* not remembered */ }
  applyStatic();
  if (typeof onLangChange === 'function') onLangChange();
}
window.addEventListener('DOMContentLoaded', () => {
  const sel = document.getElementById('langpick');
  for (const [k, v] of Object.entries(UI_LANGS)) sel.append(new Option(v, k));
  sel.value = UI_LANG; sel.addEventListener('change', () => setLang(sel.value));
  applyStatic();
});

